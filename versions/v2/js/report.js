/*
 * TLB/Scope — printable session report (report.html)
 * Builds an A4-ready document from the shared session: configuration, results
 * with working, a fully worked example, final structures, performance, a policy
 * comparison and the live verification result.
 */
(() => {
  'use strict';
  const app = window.tlbscope, E = window.TLBEngine;
  const out = document.getElementById('report');
  if (!app || !E || !out) return;
  const S = app.state, c = S.cfg, g = E.geometry(c);
  const esc = s => String(s).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch]);
  const bytes = n => (n >= 2 ** 20 ? n / 2 ** 20 + ' MiB' : n >= 1024 ? n / 1024 + ' KiB' : n + ' B');
  const pct = x => (x * 100).toFixed(1) + '%';
  const evs = app.accessEvents();
  const st = S.mmu.stats, met = S.mmu.metrics();
  const now = new Date();

  document.getElementById('printNow').addEventListener('click', () => window.print());

  const sec = (n, title, body) => `<section class="r-sec"><h2><span>${n}</span>${title}</h2>${body}</section>`;
  const kv = rows => `<table class="r-kv">${rows.map(([k, v]) => `<tr><th>${k}</th><td>${v}</td></tr>`).join('')}</table>`;

  const head = `<header class="r-head">
    <div><p class="r-kicker">Operating Systems · Module 5 · Project 45</p><h1>TLB Address Translation — Simulation Report</h1>
    <p class="r-sub">Generated by TLB/Scope v2 on ${now.toLocaleString()}</p></div>
    <div class="r-id"><span>Name</span><i></i><span>Register no.</span><i></i><span>Course / section</span><i></i></div>
  </header>`;

  if (!evs.length) {
    out.innerHTML = head + `<div class="r-empty"><h2>No session data yet</h2><p>This report is generated from your simulation. Load a scenario or translate a few addresses, then come back.</p>
      <p><a class="btn primary" href="machine.html#scenarios">Load a scenario →</a> <a class="btn" href="translate.html?addr=300">Translate 300</a></p></div>`;
    return;
  }

  const org = g.fullyAssociative ? 'fully associative' : g.directMapped ? 'direct-mapped' : `${c.tlbWays}-way set associative (${g.sets} sets)`;
  const config = kv([
    ['Virtual address', `${c.vaBits} bits (${(2 ** c.vaBits).toLocaleString('en-US')} bytes)`],
    ['Physical address', `${c.paBits} bits (${(2 ** c.paBits).toLocaleString('en-US')} bytes)`],
    ['Page size', `${bytes(c.pageSize)} → offset ${g.offsetBits} bits, VPN ${g.vpnBits} bits, PFN ${g.pfnBits} bits`],
    ['Pages / frames', `${g.pages.toLocaleString('en-US')} virtual pages · ${g.frames.toLocaleString('en-US')} physical frames`],
    ['TLB', `${c.tlbEntries} entries, ${org}, ${c.tlbPolicy} replacement`],
    ['Page table', `${c.ptLevels}-level (level bits ${g.levelBits.join(' / ')}), initial mapping: ${c.mapping}`],
    ['Page faults', c.faultMode === 'demand' ? `demand paging, ${c.framePolicy} frame replacement` : 'reported only (no page-in)'],
    ['Processes', `${c.processes}${c.processes > 1 ? `, context switch: ${c.contextMode === 'asid' ? 'ASID-tagged entries' : 'TLB flush'}` : ''}`],
    ['Timing', `t = ${c.t} ns, m = ${c.m} ns, fault service S = ${c.faultTime} ns`],
  ]);

  const model = E.eat({ h: met.hitRatio, t: c.t, m: c.m, levels: c.ptLevels, p: c.faultMode === 'demand' ? met.faultRate : 0, S: c.faultTime });
  const summary = `<div class="r-kpis">
      <div><b>${st.accesses}</b><span>translations</span></div><div><b>${pct(met.hitRatio)}</b><span>TLB hit ratio (${st.hits} hits)</span></div>
      <div><b>${st.misses}</b><span>TLB misses / walks</span></div><div><b>${st.pageFaults}</b><span>page faults${c.faultMode === 'demand' ? ` (${st.faultsServiced} serviced)` : ''}</span></div>
      <div><b>${st.protFaults}</b><span>protection faults</span></div><div><b>${st.tlbEvictions}</b><span>TLB evictions</span></div>
      <div><b>${met.measuredEAT.toFixed(2)} ns</b><span>measured EAT</span></div><div><b>${model.error ? '—' : model.total.toFixed(2) + ' ns'}</b><span>modelled EAT at measured h</span></div>
    </div>
    <p class="r-note">EAT model: h(t + m) + (1 − h)(t + (k+1)m)${c.faultMode === 'demand' ? ' + p·S' : ''} = ${met.hitRatio.toFixed(4)}(${c.t} + ${c.m}) + ${(1 - met.hitRatio).toFixed(4)}(${c.t} + ${c.ptLevels + 1}·${c.m})${c.faultMode === 'demand' ? ` + ${met.faultRate.toFixed(4)}·${c.faultTime}` : ''}${model.error ? '' : ` = <b>${model.total.toFixed(2)} ns</b>`}. Without a TLB every access would cost ${(c.ptLevels + 1) * c.m} ns.</p>`;

  const LIMIT = 60;
  const rows = evs.slice(0, LIMIT).map((e, i) => `<tr class="o-${e.outcome}"><td>${i + 1}</td><td>${c.processes > 1 ? 'P' + e.pid + ' ' : ''}${e.write ? 'W' : 'R'}</td><td>${e.addr}</td>
      <td>⌊${e.addr} / ${c.pageSize}⌋ = <b>${e.vpn}</b></td><td>${e.offset}</td><td><span class="r-pill">${e.outcome}</span></td>
      <td>${e.pfn === null || e.pfn === undefined ? '—' : e.pfn}</td><td>${e.pa === null || e.pa === undefined ? '—' : `${e.pfn} × ${c.pageSize} + ${e.offset} = <b>${e.pa}</b>`}</td><td>${e.cost}</td></tr>`).join('');
  const table = `<table class="r-table"><thead><tr><th>#</th><th>Op</th><th>VA</th><th>VPN = ⌊VA / S⌋</th><th>Offset</th><th>Result</th><th>PFN</th><th>PA = PFN × S + offset</th><th>ns</th></tr></thead><tbody>${rows}</tbody></table>
    ${evs.length > LIMIT ? `<p class="r-note">Showing the first ${LIMIT} of ${evs.length} translations. Export the full log as CSV from the Analytics page.</p>` : ''}`;

  const last = app.currentRecord();
  const worked = last ? `<p class="r-note">The most recent translation (VA ${last.addr}, result <b>${last.outcome}</b>), derived step by step:</p>
    <ol class="r-steps">${app.stepsFor(last).map(s => `<li>${s.text}</li>`).join('')}</ol>` : '';

  const tlbRows = S.mmu.tlbEntries().map(e => `<tr><td>${e.set}</td><td>${e.way}</td><td>${c.processes > 1 ? 'P' + e.asid : '—'}</td><td>${e.vpn}</td><td>${e.pfn}</td><td>${e.writable ? 'RW' : 'RO'}${e.dirty ? ', dirty' : ''}</td><td>${e.insertedAt}</td><td>${e.lastUse}</td><td>${e.uses}</td></tr>`).join('');
  const used = S.mmu.frames.filter(f => f.pid >= 0);
  const structures = `<table class="r-table"><thead><tr><th>Set</th><th>Way</th><th>ASID</th><th>VPN</th><th>PFN</th><th>Bits</th><th>Inserted</th><th>Last use</th><th>Uses</th></tr></thead><tbody>${tlbRows || '<tr><td colspan="9">TLB is empty</td></tr>'}</tbody></table>
    <p class="r-note">Physical memory: ${used.length} of ${g.frames} frames in use${used.length ? ': ' + used.slice(0, 24).map(f => `F${f.pfn}←${c.processes > 1 ? 'P' + f.pid + ':' : ''}${f.vpn}`).join(', ') + (used.length > 24 ? ', …' : '') : ''}.</p>`;

  let lab = '';
  try {
    const ops = S.ops.filter(o => o.type === 'access');
    if (ops.length && ops.length <= 4000) {
      const res = E.compare(c, ops, undefined, [1, 2, 3, 4, 8, 16, 32]);
      lab = `<table class="r-table r-lab"><thead><tr><th>Policy</th>${res.sizes.map(s => `<th>${s}</th>`).join('')}</tr></thead><tbody>${res.rows.map(r => `<tr><td>${r.policy}</td>${r.points.map(p => `<td>${p.hitRatio === null ? '—' : (p.hitRatio * 100).toFixed(1)}</td>`).join('')}</tr>`).join('')}</tbody></table>
        <p class="r-note">TLB hit % for the session trace (${ops.length} accesses) at 1–32 entries, fully associative. ${res.anomalies.length ? `<b>Belady's anomaly observed:</b> ${res.anomalies.map(a => `${a.policy} ${a.from}→${a.to} entries, misses ${a.missesFrom}→${a.missesTo}`).join('; ')}.` : 'No Belady anomaly on this trace.'} OPT is the theoretical optimum.</p>`;
    }
  } catch (e) { lab = `<p class="r-note">Policy comparison unavailable: ${esc(e.message)}</p>`; }

  let verify = '';
  if (window.TLBSuite) {
    const { tests } = window.TLBSuite(E);
    const groups = new Map();
    let pass = 0;
    const t0 = performance.now();
    tests.forEach(t => { let ok = true; try { t.fn(); } catch (e) { ok = false; } if (ok) pass++; const gr = groups.get(t.group) || [0, 0]; gr[0] += ok; gr[1]++; groups.set(t.group, gr); });
    verify = `<p class="r-verdict ${pass === tests.length ? 'ok' : 'bad'}"><b>${pass} / ${tests.length}</b> automated tests passed (${tests.filter(t => t.edge).length} edge cases) in ${(performance.now() - t0).toFixed(0)} ms, run live while generating this report.</p>
      <table class="r-table"><thead><tr><th>Test group</th><th>Passed</th></tr></thead><tbody>${[...groups].map(([k, v]) => `<tr><td>${esc(k)}</td><td>${v[0]} / ${v[1]}</td></tr>`).join('')}</tbody></table>`;
  }

  out.innerHTML = head +
    sec('1', 'Machine configuration', config) +
    sec('2', 'Results summary', summary) +
    sec('3', 'Translations with working', table) +
    (worked ? sec('4', 'Worked example', worked) : '') +
    sec(worked ? '5' : '4', 'Final TLB and memory state', structures) +
    (lab ? sec(worked ? '6' : '5', 'Replacement policy comparison', lab) : '') +
    (verify ? sec('✓', 'Verification', verify) : '') +
    `<section class="r-sec r-sign"><div><i></i><span>Student signature</span></div><div><i></i><span>Faculty signature</span></div><div><i></i><span>Date</span></div></section>`;
})();
