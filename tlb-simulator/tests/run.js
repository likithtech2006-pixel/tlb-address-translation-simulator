#!/usr/bin/env node
/* Node runner for the shared suite:  node tests/run.js  [--md]  */
'use strict';
const path = require('path');
const fs = require('fs');
const E = require('../js/engine.js');
const { tests } = require('./suite.js')(E);

const writeMd = process.argv.includes('--md');
const results = [];
const t0 = process.hrtime.bigint();
for (const t of tests) {
  const s = process.hrtime.bigint();
  let error = null;
  try { t.fn(); } catch (e) { error = e; }
  results.push({ group: t.group, name: t.name, edge: t.edge, pass: !error, error: error && error.message, ms: Number(process.hrtime.bigint() - s) / 1e6 });
}
const totalMs = Number(process.hrtime.bigint() - t0) / 1e6;

const green = s => `\x1b[32m${s}\x1b[0m`, red = s => `\x1b[31m${s}\x1b[0m`, dim = s => `\x1b[2m${s}\x1b[0m`;
let group = '';
for (const r of results) {
  if (r.group !== group) { group = r.group; console.log('\n' + group); }
  console.log(`  ${r.pass ? green('✓') : red('✗')} ${r.name}${r.edge ? dim(' [edge]') : ''}${r.pass ? '' : '\n      ' + red(r.error)}`);
}
const passed = results.filter(r => r.pass).length;
const edges = results.filter(r => r.edge).length;
console.log(`\n${passed === results.length ? green('PASS') : red('FAIL')}  ${passed}/${results.length} tests (${edges} edge cases) in ${totalMs.toFixed(1)} ms`);

if (writeMd) {
  const groups = [...new Set(results.map(r => r.group))];
  const lines = [
    '# Automated test results',
    '',
    `Generated by \`npm test\` (\`node tests/run.js --md\`) on ${new Date().toISOString().slice(0, 10)} with Node ${process.version}.`,
    '',
    `**Result: ${passed} / ${results.length} passed** · ${edges} of them are edge cases · total ${totalMs.toFixed(1)} ms`,
    '',
    '| Group | Passed |', '|---|---|',
    ...groups.map(g => { const rs = results.filter(r => r.group === g); return `| ${g} | ${rs.filter(r => r.pass).length} / ${rs.length} |`; }),
    '',
  ];
  let n = 0;
  for (const g of groups) {
    lines.push(`## ${g}`, '', '| # | Test case | Type | Result |', '|---|---|---|---|');
    for (const r of results.filter(x => x.group === g)) {
      lines.push(`| ${++n} | ${r.name.replace(/\|/g, '\\|')} | ${r.edge ? 'Edge' : 'Functional'} | ${r.pass ? 'PASS' : 'FAIL — ' + r.error} |`);
    }
    lines.push('');
  }
  fs.writeFileSync(path.join(__dirname, '..', 'TEST_RESULTS.md'), lines.join('\n'));
  console.log(dim('Wrote TEST_RESULTS.md'));
}
process.exitCode = passed === results.length ? 0 : 1;
